		заблокировать или уничтожить, отозвать согласие и обжаловать действия Оператора в Роскомнадзоре
		или в суде. Оператор отвечает на запрос в течение 10 рабочих дней.
	</p>
	{#if channels.length > 0}
		<p>Чтобы отправить запрос, напишите или позвоните Оператору: {channels.join(', ')}.</p>
