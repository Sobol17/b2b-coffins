	// The subject writes to the operator by the channels the workshop has filled in settings.
	const channels = $derived(
		[
			data.contacts.operator?.email ? `на почту ${data.contacts.operator.email}` : null,
			data.contacts.address ? `письмом по адресу ${data.contacts.address}` : null,
			data.contacts.phone ? `по телефону ${data.contacts.phone}` : null
		].filter((line) => line !== null)
	);
</script>

<LegalDocument
	title="Политика обработки персональных данных"
	contacts={data.contacts}
	site={data.site}
>
	<h2>1. Общие положения</h2>
	<p>
		Политику издал {who} (далее Оператор) по Федеральному закону от 27.07.2006 № 152-ФЗ «О персональных
		данных». Политика действует для данных, которые Оператор получает через сайт {data.site} и портал
		контрагента на нём. Оператор публикует политику на этой странице, и любой посетитель сайта может её
		прочитать.
	</p>

	<h2>2. Чьи данные и какие</h2>
	<ul>
		<li>
			Сотрудники контрагентов с учётной записью в портале: фамилия, имя, отчество, электронная
			почта, телефон, роль в организации.
		</li>
		<li>
			Контактные лица на адресах доставки: имя и телефон, которые контрагент указал в портале.
		</li>
		<li>
			Лицо, для которого изготавливается изделие: фамилия, имя и отчество, которые контрагент указал
			в заявке.
		</li>
		<li>
			Все пользователи портала: IP-адрес и сведения о браузере при входе, журнал действий в портале,
			данные подписки на push-уведомления, если пользователь их включил.
		</li>
	</ul>
	<p>
		Посетитель открытой части сайта не заполняет форм. Оператор получает от него только cookie по
		соглашению об использовании cookie.
	</p>

