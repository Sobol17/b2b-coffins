	<ul>
		<li>Выдать сотруднику контрагента доступ к порталу и восстановить доступ.</li>
		<li>Принять, изготовить и доставить заказ по договору поставки.</li>
		<li>Сообщить о ходе заявки уведомлением в портале и push-уведомлением.</li>
		<li>Защитить учётные записи от подбора пароля и чужого входа.</li>
	</ul>

	<h2>4. Правовые основания</h2>
	<p>
		Оператор обрабатывает данные для исполнения договора поставки с контрагентом (пункт 5 части 1
		статьи 6 Закона № 152-ФЗ), для защиты своих прав и законных интересов (пункт 7 части 1 статьи 6)
		и с согласия субъекта, когда закон его требует. Контрагент, который вносит в портал данные своих
		сотрудников и других людей, подтверждает, что получил их согласие на передачу данных Оператору.
	</p>

	<h2>5. Что Оператор делает с данными</h2>
	<p>
		Оператор собирает, записывает, систематизирует, хранит, уточняет, использует, обезличивает,
		блокирует, удаляет и уничтожает данные с использованием средств автоматизации. Оператор не
		продаёт данные и не передаёт их для рекламы. Доступ к данным получают сотрудники Оператора,
		которым он нужен по работе, и лица, которые по поручению Оператора обслуживают сервер сайта.
	</p>

	<h2>6. Сроки хранения</h2>
	<p>
		Оператор хранит данные учётной записи, пока она действует и действует договор с контрагентом.
